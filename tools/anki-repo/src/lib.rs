//! `anki-repo` — toolkit для CrowdAnki-экспортов репозитория Anki-decks.
//!
//! Библиотечная часть отделена от границы исполняемого файла: тонкие
//! [`crate::cli`] и [`crate::run`] находятся снаружи, а загрузка CrowdAnki,
//! обход дерева, индексы, предметные операции, проверки и контракты вывода
//! тестируются напрямую.
//!
//! `inspect`, `find`, `stats`, `validate`, `qa`, `review`, `models` и
//! `visual-report` только читают. `review-check` тоже ничего не пишет: он
//! проверяет предложения внешнего рецензента и собирает из них запрос для `edit`.
//!
//! Запись выполняется только при явном `--apply`:
//!
//! - [`ops::edit`] меняет значения уже существующих полей уже существующих
//!   заметок;
//! - [`ops::create`] добавляет новые заметки в уже существующую колоду и модель.
//!   По умолчанию ссылки на медиа запрещены. Правила в `.anki-repo/create.yaml`
//!   могут разрешить проверенные изображения домена для точных `crowdanki_uuid`
//!   и имени поля; произвольные ссылки на медиа запрещены. При таком разрешении
//!   `create` сначала размещает проверенные байты в `media/`, затем публикует
//!   изменения `media_files` и заметки в каноническом `deck.json` под общей
//!   блокировкой каталога экспорта. Если публикация JSON не удалась, уже
//!   размещённые проверенные файлы остаются для безопасного повторного
//!   использования;
//! - [`ops::retire`] дописывает тег вывода из обращения к тегам уже
//!   существующей заметки: физического удаления заметок в toolkit'е нет;
//! - [`ops::migrate_media`] меняет только доказанные ссылки в уже существующих
//!   заметках. Владелец домена подтверждает точную пару `AssetIdentity` и имя
//!   legacy-файла, а команда проверяет всех потребителей в полях заметок, `qfmt`,
//!   `afmt` и CSS. При `--apply` она размещает проверенный канонический файл,
//!   публикует `deck.json` и лишь затем удаляет точный legacy-файл.
//!
//! `edit` и `retire` меняют только канонический `deck.json`. `create` размещает
//! только явно разрешённые проверенные файлы, а `migrate-media` — только
//! доказанные канонические и legacy-файлы. Ни одна команда не удаляет и не
//! перемещает сущности экспорта, не создаёт колоды, модели и конфигурации и не
//! меняет идентификаторы (`crowdanki_uuid`, `guid`, `note_model_uuid`,
//! `deck_config_uuid`).

